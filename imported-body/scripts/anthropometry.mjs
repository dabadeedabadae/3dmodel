// I-68: how body measurements move together, from ANSUR II (U.S. Army 2012, men, public domain).
//   node imported-body/scripts/anthropometry.mjs path/to/ANSUR_II_MALE_Public.csv
// The CSV is not kept in git (https://www.openlab.psu.edu/ansur2/). Each variable is taken as the log of the ratio to
// its mean, so a coefficient reads as "1 % more X goes with b % more Y". Writes the means, standard deviations and
// covariance to imported-body/src/proportions.data.ts and a readable summary to imported-body/reports/.
import { readFileSync, writeFileSync } from 'node:fs';

const file = process.argv[2];
if (!file) { console.error('укажите путь к ANSUR_II_MALE_Public.csv'); process.exit(1); }
const lines = readFileSync(file, 'latin1').trim().split(/\r?\n/);
const head = lines[0].split(',').map((h) => h.trim().replace(/^﻿/, '').toLowerCase());
/** slider name → ANSUR II column (millimetres; weightkg is in tenths of a kilogram) */
const VARS = {
  stature: 'stature', weight: 'weightkg',
  chest: 'chestcircumference', waist: 'waistcircumference', hip: 'buttockcircumference',
  shoulders: 'bideltoidbreadth', arms: 'bicepscircumferenceflexed', thighs: 'thighcircumference',
};
const names = Object.keys(VARS);
const col = names.map((n) => { const i = head.indexOf(VARS[n]); if (i < 0) throw new Error('нет столбца ' + VARS[n]); return i; });
const rows = [];
for (const l of lines.slice(1)) {
  const c = l.split(',');
  const v = col.map((i) => Number(c[i]));
  if (v.every((x) => Number.isFinite(x) && x > 0)) rows.push(v);
}
const N = rows.length, K = names.length;
const raw = names.map((_, j) => rows.reduce((s, r) => s + r[j], 0) / N);
// geometric means: the log-ratio is then centred
const gm = names.map((_, j) => Math.exp(rows.reduce((s, r) => s + Math.log(r[j]), 0) / N));
const X = rows.map((r) => r.map((v, j) => Math.log(v / gm[j])));
const cov = names.map((_, a) => names.map((_, b) => X.reduce((s, r) => s + r[a] * r[b], 0) / (N - 1)));
const sd = cov.map((r, i) => Math.sqrt(r[i]));
const corr = cov.map((r, a) => r.map((v, b) => v / (sd[a] * sd[b])));
const r3 = (v) => Number(v.toFixed(3));
const r6 = (v) => Number(v.toPrecision(6));

const data = { source: 'ANSUR II, men, n=' + N, names, mean_mm: names.map((n, j) => r6(n === 'weight' ? raw[j] / 10 : raw[j])), sd: sd.map(r6), cov: cov.map((r) => r.map(r6)) };
writeFileSync('imported-body/src/proportions.data.ts', `// Generated by imported-body/scripts/anthropometry.mjs from ANSUR II (men, n=${N}); do not edit by hand.
// Variables are ln(value / geometric mean); mean_mm holds the arithmetic means (weight in kg) for reference.
export const PROPORTIONS = ${JSON.stringify(data, null, 2)} as const;
`);

// readable summary: correlations, and the slope "1 % of the row variable → b % of the column variable"
const pad = (s, n = 9) => String(s).padStart(n);
let md = `# Связи замеров тела (ANSUR II, мужчины, n=${N})\n\nСгенерировано \`imported-body/scripts/anthropometry.mjs\`. Переменные — логарифм отношения к среднему.\n\n`;
md += `| замер | среднее | разброс (1 SD) |\n|---|---|---|\n` + names.map((n, j) => `| ${n} | ${n === 'weight' ? (raw[j] / 10).toFixed(1) + ' кг' : (raw[j] / 10).toFixed(1) + ' см'} | ±${(sd[j] * 100).toFixed(1)} % |`).join('\n');
md += `\n\n## Корреляции\n\n|   | ${names.join(' | ')} |\n|${'---|'.repeat(K + 1)}\n` + names.map((n, a) => `| ${n} | ${corr[a].map((v) => v.toFixed(2)).join(' | ')} |`).join('\n');
md += `\n\n## Наклоны: +1 % в строке → столько % в столбце (остальное не задано)\n\n|   | ${names.join(' | ')} |\n|${'---|'.repeat(K + 1)}\n` + names.map((n, a) => `| ${n} | ${names.map((_, b) => (cov[a][b] / cov[a][a]).toFixed(2)).join(' | ')} |`).join('\n') + '\n';
writeFileSync('imported-body/reports/stage-I68-proportions.md', md);
console.log(md);
console.log(JSON.stringify({ n: N, sd: Object.fromEntries(names.map((n, j) => [n, r3(sd[j])])) }));
